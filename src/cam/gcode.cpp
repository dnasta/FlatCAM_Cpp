std::string laserPathsGCode(const PathJob& job, const GCodeOptions& opt) {
    std::ostringstream out;
    out << flavorHeader(opt.flavor);
    out << "(Laser mode.)\n\n";
    out << "(Feedrate: " << number(opt.feedXY, opt.feedDecimals) << " mm/min)\n";
    out << "(Feedrate rapids: 1500 mm/min)\n\n";
    out << "(Z Focus: " << number(opt.zFocus, opt.decimals) << " mm)\n";
    out << "(Steps per circle: 64)\n";
    out << "(Preprocessor Geometry: GRBL_laser)\n\n";
    if (job.bounds.valid) {
        out << "(X range: " << number(job.bounds.xmin, opt.decimals) << " ... "
            << number(job.bounds.xmax, opt.decimals) << " mm)\n";
        out << "(Y range: " << number(job.bounds.ymin, opt.decimals) << " ... "
            << number(job.bounds.ymax, opt.decimals) << " mm)\n\n";
    }
    out << "(Laser Power - Spindle Speed: " << number(opt.laserPower, 1) << ")\n\n";
    out << "G00 Z" << number(opt.zFocus, opt.decimals) << "\n\n";
    out << "G21\nG90\nG17\nG94\n\n";
    out << "G01 F" << number(opt.feedXY, opt.feedDecimals) << "\n\n";
    out << laserOffCommand(opt.flavor) << "\n";

    bool laserOn = false;
    for (const std::vector<Pt>& path : job.paths) {
        if (path.size() < 2) continue;
        out << "G00 " << xy(path.front(), opt) << "\n";
        if (!laserOn) {
            out << laserOnCommand(opt.flavor, opt.laserPower) << "\n";
            laserOn = true;
        }
        for (std::size_t i = 1; i < path.size(); ++i) {
            out << "G01 " << xy(path[i], opt) << " F" << number(opt.feedXY, opt.feedDecimals) << "\n";
        }
    }
    out << laserOffCommand(opt.flavor) << "\n";
    return out.str();
}

