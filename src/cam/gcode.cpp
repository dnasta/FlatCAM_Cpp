double drillTravelDistance(const DrillJob& job, const Pt& start) {
    double total = 0.0;
    Pt current = start;
    for (const DrillTool& tool : job.tools) {
        total += holesDistance(tool.holes, current);
        if (!tool.holes.empty()) current = tool.holes.back();
        for (const auto& [slotStart, slotEnd] : tool.slotSegments) {
            total += dist(current, slotStart);
            total += dist(slotStart, slotEnd);
            current = slotEnd;
        }
    }
    return total;
}

void optimizeDrillOrder(DrillJob& job, DrillOrder order, const Pt& start) {
    if (order == DrillOrder::AsIs) return;
    Pt current = start;
    for (DrillTool& tool : job.tools) {
        if (tool.holes.size() <= 18) {
            tool.holes = exactTsp(tool.holes, current);
        } else {
            sortNearest(tool.holes, current);
            twoOpt(tool.holes, current);
            orOpt(tool.holes, current);
        }
        if (!tool.holes.empty()) current = tool.holes.back();

        std::sort(tool.slotSegments.begin(), tool.slotSegments.end(),
                  [&current](const auto& a, const auto& b) {
                      return dist(current, a.first) < dist(current, b.first);
                  });
        for (const auto& [slotStart, slotEnd] : tool.slotSegments) {
            (void)slotStart;
            current = slotEnd;
        }
    }
}

void optimizePathOrder(PathJob& job, const Pt& start) {
    if (job.paths.size() < 2) return;

    std::vector<std::vector<Pt>> remaining = job.paths;
    std::vector<std::vector<Pt>> ordered;
    ordered.reserve(job.paths.size());
    Pt current = start;

    while (!remaining.empty()) {
        std::size_t best = 0;
        bool reverse = false;
        double bestDistance = std::numeric_limits<double>::infinity();
        for (std::size_t i = 0; i < remaining.size(); ++i) {
            if (remaining[i].size() < 2) continue;
            const double dStart = dist(current, remaining[i].front());
            const double dEnd = dist(current, remaining[i].back());
            if (dStart < bestDistance) {
                bestDistance = dStart;
                best = i;
                reverse = false;
            }
            if (dEnd < bestDistance) {
                bestDistance = dEnd;
                best = i;
                reverse = true;
            }
        }
        std::vector<Pt> path = remaining[best];
        if (reverse) std::reverse(path.begin(), path.end());
        current = path.back();
        ordered.push_back(std::move(path));
        remaining.erase(remaining.begin() + static_cast<std::ptrdiff_t>(best));
    }
    job.paths = std::move(ordered);
}

