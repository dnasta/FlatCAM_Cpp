bool isLaserFlavor(GCodeFlavor flavor) {
    return flavor == GCodeFlavor::GrblLaser || flavor == GCodeFlavor::MarlinLaserFan ||
           flavor == GCodeFlavor::MarlinLaserSpindle || flavor == GCodeFlavor::ZLaser;
}

bool usesM6(GCodeFlavor flavor) {
    switch (flavor) {
        case GCodeFlavor::Default:
        case GCodeFlavor::Marlin:
        case GCodeFlavor::Repetier:
        case GCodeFlavor::Berta:
        case GCodeFlavor::Isel:
        case GCodeFlavor::IselIcp:
        case GCodeFlavor::Roland:
        case GCodeFlavor::ToolchangeManual:
        case GCodeFlavor::ToolchangeProbe:
            return true;
        default:
            return false;
    }
}

std::string flavorHeader(GCodeFlavor flavor) {
    switch (flavor) {
        case GCodeFlavor::Marlin:
        case GCodeFlavor::MarlinLaserFan:
        case GCodeFlavor::MarlinLaserSpindle:
            return "(This preprocessor is used with Marlin firmware.)\n";
        case GCodeFlavor::Grbl:
        case GCodeFlavor::GrblNoM6:
        case GCodeFlavor::GrblLaser:
            return "(This preprocessor is used with a motion controller loaded with GRBL firmware.)\n";
        case GCodeFlavor::Repetier:
            return "; This preprocessor is used with a motion controller loaded with REPETIER firmware.\n";
        case GCodeFlavor::Berta:
            return "(This preprocessor is used with a BERTA CNC router.)\n";
        case GCodeFlavor::Isel:
            return "(This preprocessor is used with a ISEL CNC router.)\n";
        case GCodeFlavor::IselIcp:
            return "; This preprocessor is used with a ISEL ICP CNC router.\nIMF_PBL flatcam\n";
        case GCodeFlavor::Roland:
            return "(This preprocessor is used with a Roland MDX-20.)\n";
        case GCodeFlavor::ToolchangeManual:
            return "(This preprocessor is used with MACH3 and manual tool change.)\n";
        case GCodeFlavor::ToolchangeProbe:
            return "(This preprocessor is used with MACH3 with probing height.)\n";
        case GCodeFlavor::ZLaser:
            return "(This preprocessor controls a laser through the Z axis.)\n";
        case GCodeFlavor::Hpgl:
            return "(HPGL plotter output generated by FlatCAM C++.)\n";
        case GCodeFlavor::LineXyz:
            return "(This preprocessor writes XYZ on every linear move.)\n";
        case GCodeFlavor::ToolchangeCustom:
            return "(Custom tool change preprocessor.)\n";
        default:
            return "(This preprocessor is the default preprocessor used by FlatCAM.)\n"
                   "(It is made to work with MACH3 compatible motion controllers.)\n";
    }
}

std::string laserOnCommand(GCodeFlavor flavor, double power) {
    std::string value = number(power, 1);
    switch (flavor) {
        case GCodeFlavor::MarlinLaserFan: return "M106 S" + value;
        case GCodeFlavor::MarlinLaserSpindle: return "M3 S" + value;
        default: return "M03 S" + value;
    }
}

std::string laserOffCommand(GCodeFlavor flavor) {
    return flavor == GCodeFlavor::MarlinLaserFan ? "M107" : "M5";
}

void replaceAll(std::string& text, const std::string& from, const std::string& to) {
    if (from.empty()) return;
    std::size_t pos = 0;
    while ((pos = text.find(from, pos)) != std::string::npos) {
        text.replace(pos, from.size(), to);
        pos += to.size();
    }
}

std::string customToolchangeCode(const GCodeOptions& opt, int tool, double diameter) {
    std::string code = opt.customToolchange;
    replaceAll(code, "{tool}", std::to_string(tool));
    replaceAll(code, "{diameter}", number(diameter, opt.decimals));
    replaceAll(code, "{z}", number(opt.zToolchange, opt.decimals));
    replaceAll(code, "{x}", number(opt.toolchangeXY ? opt.toolchangeXY->x : 0.0, opt.decimals));
    replaceAll(code, "{y}", number(opt.toolchangeXY ? opt.toolchangeXY->y : 0.0, opt.decimals));
    return code;
}

std::string number(double value, int decimals) {
    char buffer[64];
    std::snprintf(buffer, sizeof(buffer), "%.*f", decimals, value);
    return std::string(buffer);
}

std::string xy(const Pt& p, const GCodeOptions& opt) {
    return "X" + number(p.x, opt.decimals) + " Y" + number(p.y, opt.decimals);
}

double toolZCut(const DrillTool& tool, const GCodeOptions& opt) {
    return tool.zCut.value_or(opt.zCut);
}

double toolFeedZ(const DrillTool& tool, const GCodeOptions& opt) {
    return tool.feedZ.value_or(opt.feedZ);
}

void writeHeader(std::ostringstream& out, const DrillJob& job, const GCodeOptions& opt) {
    out << flavorHeader(opt.flavor);
    out << "(Generated by FlatCAM C++.)\n\n";

    out << "(TOOLS DIAMETER: )\n";
    for (const DrillTool& tool : job.tools) {
        out << "(Tool: " << tool.number << " -> Dia: " << number(tool.diameter, opt.decimals) << ")\n";
    }
    out << "\n(Z_CUT: )\n";
    for (const DrillTool& tool : job.tools) {
        out << "(Tool: " << tool.number << " -> Z_Cut: " << number(toolZCut(tool, opt), opt.decimals) << ")\n";
    }
    out << "\n(Z_MOVE: )\n";
    for (const DrillTool& tool : job.tools) {
        out << "(Tool: " << tool.number << " -> Z_Move: " << number(opt.zMove, opt.decimals) << ")\n";
    }
    if (job.bounds.valid) {
        out << "\n(X range: " << number(job.bounds.xmin, opt.decimals) << " ... "
            << number(job.bounds.xmax, opt.decimals) << ")\n";
        out << "(Y range: " << number(job.bounds.ymin, opt.decimals) << " ... "
            << number(job.bounds.ymax, opt.decimals) << ")\n";
    }
    out << "\n(Spindle Speed: " << number(opt.spindleSpeed, 0) << " RPM)\n";
    out << (opt.units == Units::Inch ? "G20\n" : "G21\n");
    out << "G90\n";
    out << "G94\n";
    if (opt.spindleSpeed > 0.0) {
        out << (opt.spindleCw ? "M03" : "M04");
        out << " S" << number(opt.spindleSpeed, 0) << "\n";
    }
    out << "G00 Z" << number(opt.zStart, opt.decimals) << "\n";
}

void writeToolChange(std::ostringstream& out, const DrillTool& tool, const GCodeOptions& opt) {
    if (opt.flavor == GCodeFlavor::ToolchangeCustom && !opt.customToolchange.empty()) {
        out << customToolchangeCode(opt, tool.number, tool.diameter) << "\n";
        out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
        return;
    }
    if (opt.includeToolChange) {
        out << "M5\n";
        out << "G00 Z" << number(opt.zToolchange, opt.decimals) << "\n";
        if (opt.toolchangeXY) {
            out << "G00 " << xy(*opt.toolchangeXY, opt) << "\n";
        }
        out << "T" << tool.number << "\n";
        if (usesM6(opt.flavor)) {
            out << "M6\n";
            out << "(MSG, Change to Tool Dia = " << number(tool.diameter, opt.decimals)
                << " ||| Total drills for tool T" << tool.number << " = "
                << (tool.holes.size() + tool.slotSegments.size()) << ")\n";
            out << "M0\n";
        } else {
            out << "(MSG, Change to Tool Dia = " << number(tool.diameter, opt.decimals) << ")\n";
        }
        out << "G00 Z" << number(opt.zToolchange, opt.decimals) << "\n";
        out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
    }
}

double toolZMove(const DrillTool& tool, const GCodeOptions& opt) {
    return tool.zMove.value_or(opt.zMove);
}

void writeHole(std::ostringstream& out, const Pt& holeIn, const DrillTool& tool, const GCodeOptions& opt) {
    const Pt hole{holeIn.x + tool.offsetX, holeIn.y + tool.offsetY};
    const double zCut = toolZCut(tool, opt);
    const double zMove = toolZMove(tool, opt);
    const double feedZ = toolFeedZ(tool, opt);
    const double peck = opt.depthPerPass;
    out << "G00 " << xy(hole, opt) << "\n";
    if (peck > 0.0 && zCut < 0.0 && std::fabs(zCut) > peck + 1e-9) {
        double z = 0.0;
        while (z > zCut + 1e-9) {
            z = std::max(zCut, z - peck);
            out << "G01 Z" << number(z, opt.decimals) << " F"
                << number(feedZ, opt.feedDecimals) << "\n";
            if (z > zCut + 1e-9) {
                out << "G00 Z" << number(zMove, opt.decimals) << "\n";
                out << "G00 " << xy(hole, opt) << "\n";
            }
        }
    } else {
        out << "G01 Z" << number(zCut, opt.decimals) << " F"
            << number(feedZ, opt.feedDecimals) << "\n";
    }
    const double dwell = tool.dwell.value_or(opt.dwellTime);
    if (dwell > 0.0) out << "G04 P" << number(dwell, opt.feedDecimals) << "\n";
    out << "G00 Z" << number(zMove, opt.decimals) << "\n";
}

void writeSlot(std::ostringstream& out, const Pt& startIn, const Pt& stopIn, const DrillTool& tool,
               const GCodeOptions& opt) {
    const Pt start{startIn.x + tool.offsetX, startIn.y + tool.offsetY};
    const Pt stop{stopIn.x + tool.offsetX, stopIn.y + tool.offsetY};
    const double zCut = toolZCut(tool, opt);
    const double zMove = toolZMove(tool, opt);
    const double feedZ = toolFeedZ(tool, opt);
    const double peck = opt.depthPerPass;
    out << "G00 " << xy(start, opt) << "\n";
    if (peck > 0.0 && zCut < 0.0 && std::fabs(zCut) > peck + 1e-9) {
        double z = 0.0;
        while (z > zCut + 1e-9) {
            z = std::max(zCut, z - peck);
            out << "G01 Z" << number(z, opt.decimals) << " F"
                << number(feedZ, opt.feedDecimals) << "\n";
            if (z > zCut + 1e-9) {
                out << "G00 Z" << number(zMove, opt.decimals) << "\n";
                out << "G00 " << xy(start, opt) << "\n";
            }
        }
    } else {
        out << "G01 Z" << number(zCut, opt.decimals) << " F"
            << number(feedZ, opt.feedDecimals) << "\n";
    }
    out << "G01 " << xy(stop, opt) << " F"
        << number(tool.feedXY.value_or(opt.feedXY), opt.feedDecimals) << "\n";
    out << "G00 Z" << number(zMove, opt.decimals) << "\n";
}

