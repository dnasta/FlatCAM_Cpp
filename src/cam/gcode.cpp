std::string pasteGCode(const PasteJob& job, const GCodeOptions& opt) {
    std::ostringstream out;
    out << "(Solder paste dispensing program generated by FlatCAM C++.)\n";
    out << "(Nozzle diameter: " << number(job.nozzleDiameter, opt.decimals) << ")\n";
    if (job.bounds.valid) {
        out << "(X range: " << number(job.bounds.xmin, opt.decimals) << " ... "
            << number(job.bounds.xmax, opt.decimals) << ")\n";
        out << "(Y range: " << number(job.bounds.ymin, opt.decimals) << " ... "
            << number(job.bounds.ymax, opt.decimals) << ")\n";
    }
    out << (opt.units == Units::Inch ? "G20\n" : "G21\n");
    out << "G90\nG94\n";
    out << "G00 Z" << number(opt.zStart, opt.decimals) << "\n";
    int currentNozzle = -1;
    for (std::size_t step = 0; step < job.points.size(); ++step) {
        const std::size_t index = job.reverse ? job.points.size() - 1 - step : step;
        const Pt& p = job.points[index];
        if (job.nozzles.size() == job.points.size() &&
            job.nozzles[index] != currentNozzle) {
            currentNozzle = job.nozzles[index];
            const double dia = currentNozzle >= 0 &&
                                       currentNozzle < static_cast<int>(job.nozzleDiameters.size())
                                   ? job.nozzleDiameters[static_cast<std::size_t>(currentNozzle)]
                                   : job.nozzleDiameter;
            out << "(Nozzle T" << (currentNozzle + 1) << " - dia "
                << number(dia, opt.decimals) << " mm)\n";
            if (opt.includeToolChange) out << "M0\n";
        }
        out << "G00 " << xy(p, opt) << "\n";
        out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
        out << "G01 Z" << number(opt.zCut, opt.decimals) << " F"
            << number(opt.feedZ, opt.feedDecimals) << "\n";
        const double dwell = job.nozzleDwells.size() == job.points.size()
                                 ? job.nozzleDwells[index]
                                 : opt.dwellTime;
        if (dwell > 0.0) out << "G04 P" << number(dwell, opt.feedDecimals) << "\n";
        out << "G01 Z" << number(opt.zEnd, opt.decimals) << " F"
            << number(opt.feedZ, opt.feedDecimals) << "\n";
    }
    out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
    if (opt.endXY) out << "G00 " << xy(*opt.endXY, opt) << "\n";
    out << "M05\nM02\n";
    return out.str();
}

std::string pathsGCode(const PathJob& job, const GCodeOptions& opt) {
    if (isLaserFlavor(opt.flavor)) return laserPathsGCode(job, opt);
    if (opt.flavor == GCodeFlavor::Hpgl) {
        std::ostringstream hpgl;
        hpgl << "IN;\nSP1;\nPU;\n";
        for (const std::vector<Pt>& path : job.paths) {
            if (path.size() < 2) continue;
            hpgl << "PU;PA" << number(path.front().x, opt.decimals) << ","
                 << number(path.front().y, opt.decimals) << ";\nPD;\n";
            for (std::size_t i = 1; i < path.size(); ++i)
                hpgl << "PA" << number(path[i].x, opt.decimals) << ","
                     << number(path[i].y, opt.decimals) << ";\n";
        }
        hpgl << "PU;\nSP0;\n";
        return hpgl.str();
    }
    if (opt.flavor == GCodeFlavor::LineXyz) {
        std::ostringstream xyz;
        xyz << flavorHeader(opt.flavor);
        xyz << (opt.units == Units::Inch ? "G20\n" : "G21\n") << "G90\n";
        for (const std::vector<Pt>& path : job.paths) {
            if (path.size() < 2) continue;
            xyz << "G00 X" << number(path.front().x, opt.decimals)
                << " Y" << number(path.front().y, opt.decimals)
                << " Z" << number(opt.zMove, opt.decimals) << "\n";
            for (std::size_t i = 1; i < path.size(); ++i)
                xyz << "G01 X" << number(path[i].x, opt.decimals)
                    << " Y" << number(path[i].y, opt.decimals)
                    << " Z" << number(opt.zCut, opt.decimals)
                    << " F" << number(opt.feedXY, opt.feedDecimals) << "\n";
        }
        return xyz.str();
    }

    std::ostringstream out;
    out << flavorHeader(opt.flavor);
    out << "(Generated by FlatCAM C++.)\n\n";

    out << "(TOOL DIAMETER: " << number(job.toolDiameter, opt.decimals) << " "
        << (opt.units == Units::Inch ? "in" : "mm") << ")\n";
    out << "(Feedrate_XY: " << number(opt.feedXY, opt.feedDecimals) << ")\n";
    out << "(Feedrate_Z: " << number(opt.feedZ, opt.feedDecimals) << ")\n";
    out << "(Z_Cut: " << number(opt.zCut, opt.decimals) << ")\n";
    out << "(Z_Move: " << number(opt.zMove, opt.decimals) << ")\n";
    if (job.bounds.valid) {
        out << "(X range: " << number(job.bounds.xmin, opt.decimals) << " ... "
            << number(job.bounds.xmax, opt.decimals) << ")\n";
        out << "(Y range: " << number(job.bounds.ymin, opt.decimals) << " ... "
            << number(job.bounds.ymax, opt.decimals) << ")\n";
    }
    out << "\n(Spindle Speed: " << number(opt.spindleSpeed, 0) << " RPM)\n";
    out << (opt.units == Units::Inch ? "G20\n" : "G21\n");
    out << "G90\n";
    out << "G94\n";
    if (opt.spindleSpeed > 0.0) {
        out << (opt.spindleCw ? "M03" : "M04") << " S" << number(opt.spindleSpeed, 0) << "\n";
    }
    out << "G00 Z" << number(opt.zStart, opt.decimals) << "\n";

    if (opt.includeToolChange && opt.flavor == GCodeFlavor::ToolchangeCustom &&
        !opt.customToolchange.empty()) {
        out << customToolchangeCode(opt, 1, job.toolDiameter) << "\n";
        out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
    } else if (opt.includeToolChange) {
        out << "M5\n";
        out << "G00 Z" << number(opt.zToolchange, opt.decimals) << "\n";
        if (opt.toolchangeXY) out << "G00 " << xy(*opt.toolchangeXY, opt) << "\n";
        out << "T1\n";
        if (usesM6(opt.flavor)) {
            out << "M6\n";
            out << "(MSG, Change to Tool Dia = " << number(job.toolDiameter, opt.decimals) << ")\n";
            out << "M0\n";
        }
        out << "G00 Z" << number(opt.zToolchange, opt.decimals) << "\n";
        out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
    }

    std::vector<double> depths;
    if (opt.depthPerPass > 0.0 && opt.zCut != 0.0) {
        const double total = std::fabs(opt.zCut);
        const int steps = std::max(1, static_cast<int>(std::ceil(total / opt.depthPerPass)));
        for (int i = 1; i <= steps; ++i) {
            depths.push_back(-std::min(total, i * opt.depthPerPass));
        }
    } else {
        depths.push_back(opt.zCut);
    }

    bool atDepth = false;
    Pt lastPoint;
    for (const std::vector<Pt>& path : job.paths) {
        if (path.size() < 2) continue;
        const bool link = opt.connectPaths && atDepth &&
                          std::hypot(path.front().x - lastPoint.x,
                                     path.front().y - lastPoint.y) <= opt.connectTolerance;
        if (!link) {
            if (atDepth) out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
            out << "G00 " << xy(path.front(), opt) << "\n";
            for (double depth : depths) {
                out << "G01 Z" << number(depth, opt.decimals) << " F"
                    << number(opt.feedZ, opt.feedDecimals) << "\n";
                for (std::size_t i = 1; i < path.size(); ++i) {
                    out << "G01 " << xy(path[i], opt) << " F"
                        << number(opt.feedXY, opt.feedDecimals) << "\n";
                }
            }
        } else {
            out << "G01 " << xy(path.front(), opt) << " F"
                << number(opt.feedXY, opt.feedDecimals) << "\n";
            for (std::size_t i = 1; i < path.size(); ++i) {
                out << "G01 " << xy(path[i], opt) << " F"
                    << number(opt.feedXY, opt.feedDecimals) << "\n";
            }
        }
        atDepth = true;
        lastPoint = path.back();
    }
    if (atDepth) out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";

    if (opt.spindleSpeed > 0.0) out << "M05\n";
    out << "G00 Z" << number(opt.zEnd, opt.decimals) << "\n";
    if (opt.endXY) out << "G00 " << xy(*opt.endXY, opt) << "\n";
    return out.str();
}

std::string pathsGCodeMulti(const std::vector<PathToolJob>& tools, const GCodeOptions& header) {
    std::ostringstream out;
    if (tools.empty()) return {};

    const bool laser = isLaserFlavor(header.flavor);
    if (laser) {
        out << "(This preprocessor is used with a motion controller loaded with GRBL firmware.)\n";
        out << "(Laser mode: M03 S<power>, no Z moves.)\n\n";
        out << "(Feedrate: " << number(header.feedXY, header.feedDecimals) << " mm/min)\n";
        out << "(Z Focus: " << number(header.zFocus, header.decimals) << " mm)\n\n";
        out << "G00 Z" << number(header.zFocus, header.decimals) << "\n";
        out << "G21\nG90\nG17\nG94\n";
        out << "G01 F" << number(header.feedXY, header.feedDecimals) << "\n";
    } else {
        out << "(Multi-tool geometry program generated by FlatCAM C++.)\n";
        for (const PathToolJob& tool : tools) {
            out << "(Tool " << tool.number << " -> Dia: " << number(tool.diameter, header.decimals)
                << ")\n";
        }
        out << "\n" << (header.units == Units::Inch ? "G20\n" : "G21\n");
        out << "G90\nG94\n";
        out << "G00 Z" << number(header.zStart, header.decimals) << "\n";
    }

    for (const PathToolJob& tool : tools) {
        const GCodeOptions& opt = tool.options;
        if (laser) {
            out << "M5\n";
            out << "G00 " << (tool.paths.empty() ? "X0 Y0" : xy(tool.paths.front().front(), opt))
                << "\n";
            out << laserOnCommand(opt.flavor, opt.laserPower) << "\n";
            for (const auto& path : tool.paths) {
                if (path.size() < 2) continue;
                out << "G00 " << xy(path.front(), opt) << "\n";
                for (std::size_t i = 1; i < path.size(); ++i)
                    out << "G01 " << xy(path[i], opt) << " F"
                        << number(opt.feedXY, opt.feedDecimals) << "\n";
            }
            out << laserOffCommand(header.flavor) << "\n";
            continue;
        }

        if (header.flavor == GCodeFlavor::ToolchangeCustom && !header.customToolchange.empty()) {
            out << customToolchangeCode(header, tool.number, tool.diameter) << "\n";
            out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
        } else {
        out << "M5\n";
        out << "G00 Z" << number(opt.zToolchange, opt.decimals) << "\n";
        out << "T" << tool.number << "\n";
        if (usesM6(header.flavor)) {
            out << "M6\n";
            out << "(MSG, Change to Tool Dia = " << number(tool.diameter, opt.decimals) << ")\n";
            out << "M0\n";
        }
        out << "G00 Z" << number(opt.zToolchange, opt.decimals) << "\n";
        }
        if (opt.spindleSpeed > 0.0) out << "M03 S" << number(opt.spindleSpeed, 0) << "\n";

        std::vector<double> depths;
        if (opt.depthPerPass > 0.0 && opt.zCut != 0.0) {
            const double total = std::fabs(opt.zCut);
            const int steps = std::max(1, static_cast<int>(std::ceil(total / opt.depthPerPass)));
            for (int i = 1; i <= steps; ++i)
                depths.push_back(-std::min(total, i * opt.depthPerPass));
        } else {
            depths.push_back(opt.zCut);
        }

        bool atDepth = false;
        Pt lastPoint;
        for (const auto& path : tool.paths) {
            if (path.size() < 2) continue;
            const bool link = opt.connectPaths && atDepth &&
                              std::hypot(path.front().x - lastPoint.x,
                                         path.front().y - lastPoint.y) <= opt.connectTolerance;
            if (!link) {
                if (atDepth) out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
                out << "G00 " << xy(path.front(), opt) << "\n";
                for (double depth : depths) {
                    out << "G01 Z" << number(depth, opt.decimals) << " F"
                        << number(opt.feedZ, opt.feedDecimals) << "\n";
                    for (std::size_t i = 1; i < path.size(); ++i)
                        out << "G01 " << xy(path[i], opt) << " F"
                            << number(opt.feedXY, opt.feedDecimals) << "\n";
                }
            } else {
                out << "G01 " << xy(path.front(), opt) << " F"
                    << number(opt.feedXY, opt.feedDecimals) << "\n";
                for (std::size_t i = 1; i < path.size(); ++i)
                    out << "G01 " << xy(path[i], opt) << " F"
                        << number(opt.feedXY, opt.feedDecimals) << "\n";
            }
            atDepth = true;
            lastPoint = path.back();
        }
        if (atDepth) out << "G00 Z" << number(opt.zMove, opt.decimals) << "\n";
    }

    if (!laser && header.spindleSpeed > 0.0) out << "M05\n";
    out << "G00 Z" << number(header.zEnd, header.decimals) << "\n";
    if (header.endXY) out << "G00 " << xy(*header.endXY, header) << "\n";
    if (laser) out << "M5\n";
    return out.str();
}

DrillJob drillJobFromExcellon(const ExcellonResult& result) {
    DrillJob job;
    job.bounds = result.bounds;
    job.tools.reserve(result.tools.size());
    for (const auto& [number, tool] : result.tools) {
        if (tool.drills.empty() && tool.slotSegments.empty()) continue;
        DrillTool drill;
        drill.number = number;
        drill.diameter = tool.diameter;
        drill.holes = tool.drills;
        drill.slotSegments = tool.slotSegments;
        job.tools.push_back(std::move(drill));
    }
    return job;
}

